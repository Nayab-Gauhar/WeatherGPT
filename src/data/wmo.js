const FALLBACK = { slug: 'partly_cloudy', icon: 'partly_cloudy', severity: 0 };

export function describeCode(code) {
  return CODE_MAP[code] ?? FALLBACK;
}

/** Localised condition text for a WMO code. */
export function conditionLabel(code, lang = 'en') {
  const { slug } = describeCode(code);
  const table = LABELS[lang] ?? LABELS.en;
  return table[slug] ?? LABELS.en[slug] ?? LABELS.en.partly_cloudy;
}

/** Icon key used by <WeatherIcon />; night variants swap sun for moon. */
export function iconFor(code, isDay = true) {
  const { icon } = describeCode(code);
  return isDay ? icon : `${icon}_night`;
}

export function severityFor(code) {
  return describeCode(code).severity;
}

/** True when the code implies any liquid/solid precipitation. */
export function isWet(code) {
  const { slug } = describeCode(code);
  return !['clear', 'mostly_clear', 'partly_cloudy', 'overcast', 'fog', 'rime_fog'].includes(slug);
}

